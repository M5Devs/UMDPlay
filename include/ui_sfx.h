#pragma once

#include <cstdint>
#include <vector>

// Procedural Windows Media Center inspired UI sounds. Nothing is bundled: every
// cue is synthesized from sine harmonics with an exponential envelope at
// 44100 Hz stereo, so the binary carries no third-party sample data.
//
// Playback uses a dedicated SDL audio device, separate from the movie/music
// device owned by UiManager, so a chime never disturbs (or is disturbed by)
// playback. The class is headless-safe: with no audio hardware (e.g.
// SDL_AUDIODRIVER=dummy) init() still succeeds in generating the buffers and
// play() becomes a no-op.
namespace umdplay {

enum class UiCue {
    None = -1,  // no cue (default for UI intents)
    Navigate,   // soft glassy tick: move between strips / cards / buttons
    Select,     // warm two-tone chime: Enter / tap / Play
    Back,       // soft descending tone: Esc / Back / Cancel
    Startup,    // welcoming chord on launch
    Count
};

class UiSfx {
public:
    UiSfx();
    ~UiSfx();

    UiSfx(const UiSfx&) = delete;
    UiSfx& operator=(const UiSfx&) = delete;

    // Open the dedicated SDL audio device. The cue buffers are generated by the
    // constructor regardless, so this only controls whether play() can emit.
    // Never fatal: returns true when a device was opened, false otherwise.
    bool init();
    void close();

    // True when a device is open and cues can be heard.
    bool ready() const { return m_dev != 0; }

    // Queue a cue. No-op when there is no device, sounds are disabled, or the
    // player is muted.
    void play(UiCue cue);

    void set_muted(bool m)   { m_muted = m; }
    bool muted() const       { return m_muted; }
    void set_enabled(bool e) { m_enabled = e; }
    bool enabled() const     { return m_enabled; }

    // --- Introspection (offline / tests) ---
    // Number of playable cues (Navigate..Startup); UiCue::None is excluded.
    static constexpr int kCueCount = 4;
    static constexpr int sample_rate() { return 44100; }
    static constexpr int channels()    { return 2; }
    static constexpr int cue_count()   { return kCueCount; }

    static const char* cue_name(UiCue cue);

    // Interleaved S16 stereo PCM in the canonical 44100 Hz format. Generated
    // once at construction; stable for the object's lifetime.
    const std::vector<int16_t>& pcm(UiCue cue) const;

    // Normalized float rendition of a cue in [-1, 1] (interleaved stereo).
    // Pure and deterministic, so tests can assert finiteness without a device.
    static std::vector<float> render_float(UiCue cue);

private:
    std::vector<int16_t> m_pcm[kCueCount];
    uint32_t m_dev = 0;
    bool     m_muted = false;
    bool     m_enabled = true;
    bool     m_own_audio_subsystem = false;

    void queue(const std::vector<int16_t>& buf);
};

}  // namespace umdplay
