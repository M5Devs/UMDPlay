/**
 * Build a canonical Huffman lookup table from per-symbol code lengths.
 *
 * Codes are assigned in the order given (matching FFmpeg's
 * ff_vlc_init_from_lengths, which the ATRAC3+ codebooks depend on), and each
 * symbol is expanded into a flat 2^nb_bits lookup table.
 */
int vlc_init_from_lengths(VLC* vlc, int nb_bits, int nb_codes,
                          const uint8_t* lens, const uint8_t* symbols)
{
    if (!vlc || !vlc->table || nb_bits <= 0 || nb_bits > 16)
        return AT3P_ERR_INVALIDDATA;

    const int size = 1 << nb_bits;
    if (vlc->table_allocated < size)
        return AT3P_ERR_INVALIDDATA;

    memset(vlc->table, 0, static_cast<size_t>(size) * sizeof(VLCElem));

    uint64_t code = 0;
    for (int i = 0; i < nb_codes; i++) {
        const int len = lens[i];
        if (len == 0)
            continue;
        if (len < 0 || len > nb_bits)
            return AT3P_ERR_INVALIDDATA;

        const uint32_t index = static_cast<uint32_t>(code >> (32 - nb_bits));
        const int span = 1 << (nb_bits - len);
        if (index + span > static_cast<uint32_t>(size))
            return AT3P_ERR_INVALIDDATA;  // overdetermined tree

        for (int k = 0; k < span; k++) {
            vlc->table[index + k].sym = static_cast<int16_t>(symbols[i]);
            vlc->table[index + k].len = static_cast<int8_t>(len);
        }
        code += 1ULL << (32 - len);
    }

    vlc->bits       = nb_bits;
    vlc->table_size = size;
    return 0;
}

